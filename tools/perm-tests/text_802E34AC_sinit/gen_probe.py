#!/usr/bin/env python3
# Generate probe .cpp for text_802E34AC synthesis from storm_map.json (no manual transcription)
import json, re

ROOT = '/Users/scott/Hermes/pso-decomp/pso-decomp-f7'
m = json.load(open(ROOT + '/tools/perm-tests/text_802E34AC_sinit/storm_map.json'))
pool = m['pool']  # 147 words, frag-rel +0x18..0x264: triples {0,-1,fn}

assert len(pool) == 147 and pool[0] == 0 and pool[1] == 0xFFFFFFFF
triples = []
for i in range(49):
    a, b, f = pool[3*i], pool[3*i+1], pool[3*i+2]
    assert a == 0 and b == 0xFFFFFFFF, (i, hex(a), hex(b))
    triples.append(f)

# name via symbols.txt
names = {}
for ln in open(ROOT + '/config/GPOE8P/psov3/symbols.txt'):
    mm = re.match(r'(\S+) = \S+:0x([0-9A-Fa-f]+);', ln)
    if mm: names.setdefault(int(mm.group(2), 16), mm.group(1))

CLASS = 'TAdSinglePlyChrSelectGC'
ARGS = {'Fv': '', 'FPv': 'void *', 'Fl': 'long', 'Fi': 'int'}
members = {}   # (mem,sig) -> era sym
from collections import Counter
sigcount = Counter()
raw = []
for i, f in enumerate(triples):
    nm = names.get(f)
    assert nm, (i, hex(f), nm)
    if nm.startswith(CLASS + '__sub_'):
        mem, sig = nm[len(CLASS)+2:], 'Fv'
    else:
        mm = re.match(r'(.+)__23TAdSinglePlyChrSelectGC(F.*)$', nm)
        assert mm, (i, nm)
        mem, sig = mm.group(1), mm.group(2)
    members[(mem, sig)] = nm
    sigcount[mem] += 1
    raw.append((mem, sig))
slots = []
for mem, sig in raw:
    if sigcount[mem] > 1:
        slots.append(f'(Handler)(void (TAdSinglePlyChrSelectGC::*)({ARGS[sig].strip()}))&TAdSinglePlyChrSelectGC::{mem}')
    else:
        slots.append('(Handler)&TAdSinglePlyChrSelectGC::' + mem)

# slot 30 = null (no pool entry) — the slots list above has 49 entries; instance = 49 + 1 null at idx 30
final = slots[:30] + ['0'] + slots[30:]
assert len(final) == 50

decls = []
for (mem, sig), era in sorted(members.items()):
    args = {'Fv': '', 'FPv': 'void *', 'Fl': 'long', 'Fi': 'int'}[sig]
    decls.append(f'    void {mem}({args});')
    # overloads with same member name differ in args — keep both

out = []
out.append('// Probe V1: MWCC __sinit synthesis for era fn_802E34AC (gate 0x638).')
out.append('// Generated by gen_probe.py from storm_map.json — do not hand-edit.')
out.append('#include "types.h"')
out.append('')
out.append('extern "C" {')
out.append('extern const f32 lbl_80472930[2];')
out.append('}')
out.append('')
out.append(f'class {CLASS} {{')
out.append('public:')
out += sorted(set(decls))
out.append('};')
out.append('')
out.append(f'typedef void ({CLASS}::*Handler)();')
out.append('')
out.append('// boot-seeded char-select layout geometry (69C rule: extern-const f32 exprs force runtime init)')
out.append('__declspec(section ".data") static f32 lbl_804E3040[2] = {')
out.append('    0.5f * (640.0f - lbl_80472930[0]), 90.0f,')
out.append('};')
out.append('__declspec(section ".data") static f32 lbl_804E3048[2] = {')
out.append('    20.0f + lbl_804E3040[0], 10.0f + (lbl_804E3040[1] + lbl_80472930[1]),')
out.append('};')
out.append('static f32 lbl_805D68E0 = lbl_80472930[0] - 40.0f;')
out.append('__declspec(section ".data") static f32 lbl_804E3050[2] = {')
out.append('    0.5f * lbl_80472930[0] + lbl_804E3040[0], lbl_804E3048[1] - 85.0f,')
out.append('};')
out.append('')
out.append('// 50-slot state-action handler table (idx 30 = null action; consumer null-checks it)')
out.append(f'static Handler lbl_804E32A4[{len(final)}] = {{')
for i in range(0, len(final), 2):
    row = ', '.join(final[i:i+2])
    out.append('    ' + row + (',' if i + 2 < len(final) else ','))
out.append('};')
out.append('')

open(ROOT + '/tools/perm-tests/text_802E34AC_sinit/probe_802E34AC_v1.cpp', 'w').write('\n'.join(out))
print('probe written; members:', len(members), 'slots:', len(final))
print('null slot era check: pool[3*29]=', hex(triples[29]))
# ordered slot list for FINDINGS
json.dump([{'slot': i, 'init': s} for i, s in enumerate(final)], open(ROOT + '/tools/perm-tests/text_802E34AC_sinit/slots.json', 'w'))
